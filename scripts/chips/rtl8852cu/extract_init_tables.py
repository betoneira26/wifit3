"""Extract rtw8852c init tables from kernel C source to Python data files.

Source: /usr/src/rtw89-git/rtw8852c_table.c
Output: src/wifit3/chips/rtl8852cu/assets/{bb,bb_gain,nctl,rf_a,rf_b}_tbl.py
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SRC = Path("/usr/src/rtw89-git/rtw8852c_table.c")
OUT_DIR = ROOT / "src/wifit3/chips/rtl8852cu/assets"

TABLE_MAP = {
    "bb": "rtw89_8852c_phy_bb_regs",
    "bb_gain": "rtw89_8852c_phy_bb_reg_gain",
    "nctl": "rtw89_8852c_phy_nctl_regs",
    "rf_a": "rtw89_8852c_phy_radioa_regs",
    "rf_b": "rtw89_8852c_phy_radiob_regs",
}


def parse_table(text: str, c_name: str) -> list[tuple[int, int]]:
    pat = re.compile(rf"static\s+const\s+struct\s+rtw89_reg2_def\s+{c_name}\[\]\s*=\s*\{{(.*?)\}}\s*;", re.DOTALL)
    m = pat.search(text)
    if not m:
        raise SystemExit(f"{c_name} not found in source")
    raw = m.group(1)
    pairs = re.findall(r"\{\s*(0x[0-9A-Fa-f]+|\d+)\s*,\s*(0x[0-9A-Fa-f]+|\d+)\s*\}", raw)
    return [(int(a, 0), int(d, 0)) for a, d in pairs]


HEADER_TMPL = '''"""rtw8852c {name} init table — extracted from kernel rtw8852c_table.c.

Auto-generated by scripts/chips/rtl8852cu/extract_init_tables.py — DO NOT EDIT.
Entries: {count}
"""

TABLE: list[tuple[int, int]] = [
'''


def emit(name: str, pairs: list[tuple[int, int]]) -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    out = OUT_DIR / f"{name}_tbl.py"
    lines = [HEADER_TMPL.format(name=name, count=len(pairs))]
    for a, d in pairs:
        lines.append(f"    (0x{a:08X}, 0x{d:08X}),\n")
    lines.append("]\n")
    out.write_text("".join(lines), encoding="utf-8")
    print(f"  {name:8s} -> {out.relative_to(ROOT)}  ({len(pairs)} entries)")


def main() -> int:
    if not SRC.exists():
        print(f"ERROR: missing {SRC}", file=sys.stderr)
        return 1
    text = SRC.read_text(encoding="utf-8", errors="replace")
    print(f"Reading {SRC}")
    for name, c_name in TABLE_MAP.items():
        pairs = parse_table(text, c_name)
        emit(name, pairs)
    # Also ensure __init__.py exists in assets
    init_file = OUT_DIR / "__init__.py"
    if not init_file.exists():
        init_file.write_text("", encoding="utf-8")
    print("Done extracting tables.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
